/**
 * THE WALKABILITY PROOF, and the determinism proof, over real buildings from the real map.
 *
 * The owner named unreachable spots explicitly, so this suite does not sample-check a couple of
 * hand-made floors: it plans the core for hundreds of the city's own parcels, solves floors up and
 * down each of them, and asserts every walkable tile is reachable from where the player lands. The
 * second half asserts that solving the same floor twice — and solving floor 31 without ever having
 * solved floor 30 — gives byte-identical geometry.
 */
import { describe, expect, it } from 'vitest';
import { BuildingArchitecture } from '../../world/BuildingArchitecture';
import * as THREE from 'three';
import { allBuildings, type GeneratedBuilding } from '../../world/CityGen';
import { allScatteredModels } from '../../world/ModelScatter';
import { MODEL_INDEX } from '../../world/models/catalog';
import { scatterDoorFor } from './doors';
import {
  buildCore, coreBackZ, coreContinuity, LIFT_FROM_STOREYS, MIN_ROOM, TARDIS_MAX,
  type BuildingFacts, type StairClass,
} from './core';
import { solveFloor } from './floor';

const architecture = new BuildingArchitecture(new THREE.Group());
const facade = new THREE.MeshBasicMaterial();
const roof = new THREE.MeshBasicMaterial();

function factsFor(building: GeneratedBuilding): BuildingFacts | undefined {
  const profile = architecture.plan({
    x: 0, z: 0, width: building.width, depth: building.depth, height: building.height,
    style: building.style, variant: building.variant, facade, roof,
  });
  if (!profile.entrance) return undefined;
  return {
    id: `${Math.round(building.x)}:${Math.round(building.z)}`,
    x: building.x, z: building.z, heading: building.heading,
    width: building.width, depth: building.depth, height: building.height,
    style: building.style, entrance: profile.entrance.kind, doorX: profile.entrance.x,
  };
}

/** A wide, deterministic slice of the real city — every 7th parcel that carries a tagged door. */
function sample(limit: number): BuildingFacts[] {
  const out: BuildingFacts[] = [];
  const all = allBuildings();
  for (let i = 0; i < all.length && out.length < limit; i += 7) {
    const facts = factsFor(all[i]!);
    if (facts) out.push(facts);
  }
  return out;
}

/** Up to `each` parcels of EVERY structural family. A citywide stride is dominated by houses and
 *  flats, so on its own it would prove nothing about the works and the villas this pass opened. */
function perFamily(each: number): Map<string, BuildingFacts[]> {
  const out = new Map<string, BuildingFacts[]>();
  for (const building of allBuildings()) {
    const bucket = out.get(building.style) ?? [];
    if (bucket.length >= each) continue;
    const facts = factsFor(building);
    if (!facts) continue;
    bucket.push(facts);
    out.set(building.style, bucket);
  }
  return out;
}

describe('the floorplan solver', () => {
  it('leaves no unreachable spot on any floor of any building it opens', () => {
    const buildings = sample(220);
    expect(buildings.length).toBeGreaterThan(150);
    let floors = 0;
    for (const facts of buildings) {
      const core = buildCore(facts);
      // Ground, one up, one down from the top, and a floor deep in the middle of a tall building —
      // the ones a player actually reaches, plus the one nobody would have generated by hand.
      const indices = [...new Set([0, 1, Math.floor(core.storeys / 2), core.storeys - 1])]
        .filter((index) => index >= 0 && index < core.storeys);
      for (const index of indices) {
        const plan = solveFloor(facts, index, core);
        floors++;
        expect(plan.walkable, `${facts.id} floor ${index} has no floor at all`).toBeGreaterThan(20);
        expect(plan.unreachable, `${facts.id} floor ${index}: ${plan.unreachable} unreachable tiles`).toBe(0);
      }
    }
    expect(floors).toBeGreaterThan(300);
  }, 300000);

  it('gives every room a doorway onto the spine, so every room reaches the core', () => {
    for (const facts of sample(80)) {
      const core = buildCore(facts);
      const plan = solveFloor(facts, 0, core);
      expect(plan.rooms.length, `${facts.id} has no rooms`).toBeGreaterThan(0);
      if (core.layout === 'small') {
        // The honest small layout IS one room with the door straight into it: no partitions.
        expect(plan.rooms, `${facts.id} small layout must be exactly one room`).toHaveLength(1);
        expect(plan.walls, `${facts.id} small layout must have no partitions`).toHaveLength(0);
        continue;
      }
      for (const room of plan.rooms) {
        const wall = plan.walls.find((candidate) => candidate.axis === 'x'
          && candidate.gapWidth !== undefined
          && Math.abs(candidate.gapCentre! - room.doorZ) < 1e-6);
        expect(wall, `${facts.id} room ${room.id} has no doorway`).toBeDefined();
      }
    }
  }, 120000);

  it('keeps the core continuous from the street door to the top storey', () => {
    for (const facts of sample(300)) {
      expect(coreContinuity(buildCore(facts)), facts.id).toBeUndefined();
    }
  }, 120000);

  /**
   * The citywide stride is four-fifths houses and flats, so it would pass happily while every works
   * in the city generated a sealed floor. This walks every family the map zones, up and down.
   */
  it('leaves no unreachable spot in ANY structural family, works and villas included', () => {
    const families = perFamily(30);
    expect(families.size, 'the map stopped zoning a whole family').toBeGreaterThan(5);
    for (const [style, buildings] of families) {
      expect(buildings.length, `${style} has no openable parcels at all`).toBeGreaterThan(0);
      for (const facts of buildings) {
        const core = buildCore(facts);
        const indices = [...new Set([0, 1, core.storeys - 1])].filter((index) => index >= 0 && index < core.storeys);
        for (const index of indices) {
          const plan = solveFloor(facts, index, core);
          expect(plan.rooms.length, `${style} ${facts.id} floor ${index} has no rooms`).toBeGreaterThan(0);
          expect(plan.walkable, `${style} ${facts.id} floor ${index} has no floor at all`).toBeGreaterThan(20);
          expect(plan.unreachable, `${style} ${facts.id} floor ${index}: ${plan.unreachable} unreachable`).toBe(0);
        }
      }
    }
  }, 300000);

  /**
   * AND THE SAME PROOF FOR THE SCATTER PASS, which is most of the buildings outside the CBD and was
   * absent from the first version of this suite. Every model family the catalog opens — a farmhouse,
   * a barn, a spaza, a kerk — solves a floor whose every tile is reachable from the mat.
   */
  it('leaves no unreachable spot in any scattered model family either', () => {
    const perModel = new Map<string, BuildingFacts[]>();
    for (const model of allScatteredModels()) {
      if (!MODEL_INDEX.get(model.name)?.interior) continue;
      const bucket = perModel.get(model.name) ?? [];
      if (bucket.length >= 6) continue;
      const door = scatterDoorFor(model);
      if (!door) continue;
      bucket.push(door.facts);
      perModel.set(model.name, bucket);
    }
    expect(perModel.size, 'the catalog stopped opening whole model families').toBe(32);
    for (const [name, buildings] of perModel) {
      for (const facts of buildings) {
        const core = buildCore(facts);
        expect(coreContinuity(core), `${name} ${facts.id}`).toBeUndefined();
        for (const index of [...new Set([0, core.storeys - 1])]) {
          const plan = solveFloor(facts, index, core);
          expect(plan.rooms.length, `${name} ${facts.id} floor ${index} has no rooms`).toBeGreaterThan(0);
          expect(plan.walkable, `${name} ${facts.id} floor ${index} has no floor at all`).toBeGreaterThan(20);
          expect(plan.unreachable, `${name} ${facts.id} floor ${index}: ${plan.unreachable} unreachable`).toBe(0);
        }
      }
    }
  }, 600000);

  /** The owner's line, verbatim: "for a commercial building it makes sense to have a service desk,
   *  but for residentials they shouldn't have commercial furnishings." A block of flats gets a
   *  postbox wall in its lobby; an office tower keeps the desk; a house was already all home. */
  it('keeps commercial furnishings out of residential buildings', () => {
    const families = perFamily(14);
    const flats = families.get('dense-residential') ?? [];
    expect(flats.length).toBeGreaterThan(4);
    for (const facts of flats) {
      const ground = solveFloor(facts, 0);
      expect(ground.props.some((prop) => prop.shape === 'counter'),
        `${facts.id}: a service counter in a block of flats`).toBe(false);
      if (ground.rooms.some((room) => room.kind === 'lobby')) {
        expect(ground.props.some((prop) => prop.shape === 'postboxes'),
          `${facts.id}: a flats lobby with no postbox wall`).toBe(true);
      }
    }
    for (const facts of (families.get('downtown') ?? []).slice(0, 8)) {
      const ground = solveFloor(facts, 0);
      if (ground.rooms.some((room) => room.kind === 'lobby')) {
        expect(ground.props.some((prop) => prop.shape === 'counter'),
          `${facts.id}: a commercial lobby lost its desk`).toBe(true);
      }
    }
    for (const style of ['suburban', 'estate', 'rural'] as const) {
      for (const facts of (families.get(style) ?? []).slice(0, 10)) {
        const ground = solveFloor(facts, 0);
        const commercial = ground.props.filter((prop) => prop.shape === 'counter' || prop.shape === 'rack' || prop.shape === 'postboxes');
        // The handful of genuine rural farm shops (shopfront-tagged) keep their counters — a
        // padstal IS a shop. Houses proper carry none of it.
        if (facts.entrance !== 'shopfront') {
          expect(commercial, `${style} ${facts.id} has commercial furniture: ${commercial.map((p) => p.shape).join(',')}`).toHaveLength(0);
        }
      }
    }
  }, 300000);

  /** A shed must not generate a lounge, and a house must not generate a warehouse bay. */
  it('gives each family its own grammar', () => {
    const families = perFamily(12);
    const works = families.get('industrial') ?? [];
    expect(works.length).toBeGreaterThan(4);
    for (const facts of works) {
      const ground = solveFloor(facts, 0);
      expect(ground.eyebrow).toBe('WORKS');
      expect(ground.rooms.some((room) => room.kind === 'warehouse'), `${facts.id} has no bay`).toBe(true);
      const domestic = new Set(['lounge', 'bedroom', 'kitchen', 'dining', 'bathroom']);
      expect(ground.rooms.some((room) => domestic.has(room.kind)), `${facts.id} put a lounge in a works`).toBe(false);
      expect(ground.props.some((prop) => prop.shape === 'rack'), `${facts.id} has no racking`).toBe(true);
      const core = buildCore(facts);
      if (core.storeys > 1) {
        const up = solveFloor(facts, 1, core);
        expect(up.eyebrow).toBe('MEZZANINE');
      }
    }
    for (const style of ['suburban', 'estate'] as const) {
      for (const facts of families.get(style) ?? []) {
        const ground = solveFloor(facts, 0);
        expect(ground.rooms.some((room) => room.kind === 'warehouse'), `${style} generated a warehouse bay`).toBe(false);
        expect(ground.rooms.some((room) => room.kind === 'lounge'), `${style} ${facts.id} has no living room`).toBe(true);
      }
    }
  }, 300000);

  /**
   * "Entering two houses on the same street should not produce the same lounge." A house is the most
   * common building in this city, so sameness would be the first thing a player noticed.
   */
  it('does not give two houses on the same street the same interior', () => {
    const houses = (perFamily(60).get('suburban') ?? []).slice(0, 40);
    expect(houses.length).toBeGreaterThan(20);
    const signatures = new Set<string>();
    const finishes = new Set<string>();
    for (const facts of houses) {
      const core = buildCore(facts);
      const plan = solveFloor(facts, 0, core);
      finishes.add(core.finish);
      signatures.add([
        plan.rooms.length,
        plan.rooms.map((room) => room.kind).join(','),
        plan.props.length,
        plan.palette.wall.toString(16),
        plan.blurb.length,
      ].join('|'));
    }
    // Not a promise of forty unique houses — a promise that walking into two is not walking into one.
    expect(signatures.size, 'every house on the street is the same house').toBeGreaterThan(houses.length * 0.5);
    expect(finishes.size, 'every house has the same finish').toBeGreaterThan(1);
  }, 300000);

  /** "There seem to always be stairs, even on single floor buildings" — the owner. Not any more:
   *  a stair exists exactly when there is a storey for it to reach, and a lift only on tall stacks. */
  it('gives a stair only to buildings with an upstairs, and a lift only to tall ones', () => {
    let tall = 0; let single = 0; let multi = 0;
    for (const facts of sample(300)) {
      const core = buildCore(facts);
      if (core.storeys === 1) {
        single++;
        expect(core.stair, `${facts.id} is single-storey and still carries a stair shaft`).toBeUndefined();
        expect(core.lift, facts.id).toBeUndefined();
        continue;
      }
      multi++;
      expect(core.stair, `${facts.id} has ${core.storeys} storeys and no stair`).toBeDefined();
      expect(core.stair!.w).toBeGreaterThan(1.5);
      if (core.storeys >= LIFT_FROM_STOREYS) { tall++; expect(core.lift, facts.id).toBeDefined(); }
      else expect(core.lift, facts.id).toBeUndefined();
    }
    expect(tall).toBeGreaterThan(3);
    expect(single, 'the sample found no single-storey buildings at all').toBeGreaterThan(10);
    expect(multi).toBeGreaterThan(10);
  }, 120000);

  /**
   * "The stairs and elevators always seem to be in the same place" — measured as literally true:
   * zero variance in stair z, one constant lift offset, the whole stair-x distribution inside the
   * middle 40% of the plate. This asserts the seed is now genuinely SPENT on the skeleton.
   */
  it('spends the seed on the skeleton: stair x, stair depth-gap, turn direction and lift side all vary', () => {
    const cores = sample(300).map(buildCore).filter((core) => core.stair);
    expect(cores.length).toBeGreaterThan(80);
    const offsets = new Set(cores.map((core) => (core.stair!.x - core.corridorX).toFixed(2)));
    const backGaps = new Set(cores.map((core) => (core.depth / 2 - (core.stair!.z + core.stair!.d / 2)).toFixed(2)));
    const turns = new Set(cores.map((core) => core.stairDir));
    expect(offsets.size, 'every stair sits at one offset from the spine').toBeGreaterThan(20);
    expect(backGaps.size, 'every stair sits the same distance off the back wall').toBeGreaterThan(20);
    expect(turns.size, 'every switchback turns the same way').toBe(2);
    const lifted = cores.filter((core) => core.lift);
    if (lifted.length > 3) {
      const sides = new Set(lifted.map((core) => Math.sign(core.lift!.x - core.stair!.x)));
      expect(sides.size, 'every lift stands on the same side of its stair').toBe(2);
    }
  }, 120000);

  /**
   * ROUND 3: the stair is picked EARLY and can go almost anywhere — the position CLASS is the
   * first thing the seed buys, so the citywide result is multi-modal (back / mid / side / front),
   * not one smeared blob near the corridor. This asserts all four classes genuinely occur, that
   * island cores really do put rooms BEHIND the stair, and — the part that matters — that every
   * class's floors still flood-fill complete from the landing.
   */
  it('spreads the stair across position classes, and every class stays walkable', () => {
    const staired = sample(400)
      .map((facts) => ({ facts, core: buildCore(facts) }))
      .filter((entry) => entry.core.stair);
    expect(staired.length).toBeGreaterThan(100);
    const byClass = new Map<StairClass, typeof staired>();
    for (const entry of staired) {
      const list = byClass.get(entry.core.stairClass!) ?? [];
      list.push(entry);
      byClass.set(entry.core.stairClass!, list);
    }
    expect([...byClass.keys()].sort(), 'a position class never occurs in a 400-building sample')
      .toEqual(['back', 'front', 'mid', 'side']);
    // Islands really are islands: mid and front cores put a room band behind the stair.
    for (const name of ['mid', 'front'] as const) {
      for (const { facts, core } of byClass.get(name)!) {
        expect(coreBackZ(core), `${name} core ${facts.id} has no rooms behind the stair`).toBeDefined();
      }
    }
    // The spread is real, not classes-in-name-only: normalised stair x reaches past the old ±0.5
    // corridor blob, and normalised z reaches well off the back wall.
    const normX = staired.map(({ core }) => core.stair!.x / (core.width / 2));
    const normZ = staired.map(({ core }) => core.stair!.z / (core.depth / 2));
    expect(normX.filter((v) => Math.abs(v) > 0.55).length, 'no stairs near the plate edges').toBeGreaterThan(10);
    expect(normZ.filter((v) => v < 0.1).length, 'no stairs forward of mid-plate').toBeGreaterThan(10);
    // And every class proves walkable, on the ground floor, one up, and the top.
    for (const [name, list] of byClass) {
      for (const { facts, core } of list.slice(0, 12)) {
        const indices = [...new Set([0, 1, core.storeys - 1])].filter((i) => i >= 0 && i < core.storeys);
        for (const index of indices) {
          const plan = solveFloor(facts, index, core);
          expect(plan.rooms.length, `${name} ${facts.id} floor ${index} has no rooms`).toBeGreaterThan(0);
          expect(plan.unreachable, `${name} ${facts.id} floor ${index}: ${plan.unreachable} unreachable`).toBe(0);
        }
      }
    }
  }, 300000);

  /**
   * ROUND 3: the plate comes from the MODEL. Within the grammar's hard floors the interior is the
   * footprint times at most TARDIS_MAX, aspect preserved — and a building too small for even that
   * gets the honest one-room layout instead of inflation.
   */
  it('sizes the plate from the footprint, bounded tardis, honest small layouts below it', () => {
    let floored = 0;
    for (const facts of sample(400)) {
      const core = buildCore(facts);
      if (core.layout === 'small') continue; // asserted over the scatter pass below, where they live
      const bareW = Math.max(1, facts.width - 0.9);
      const bareD = Math.max(1, facts.depth - 0.9);
      // The bound: single-storey full layouts never exceed TARDIS_MAX on either axis. Multi-storey
      // may exceed it ONLY under the stair-grammar hard floor (width 15.1 / depth 12) or ceiling.
      const ratioW = core.width / bareW;
      const ratioD = core.depth / bareD;
      if (core.storeys === 1) {
        expect(ratioW, `${facts.id} single-storey width past the tardis bound`).toBeLessThanOrEqual(TARDIS_MAX + 1e-6);
        expect(ratioD, `${facts.id} single-storey depth past the tardis bound`).toBeLessThanOrEqual(TARDIS_MAX + 1e-6);
      } else if (ratioW > TARDIS_MAX + 1e-6 || ratioD > TARDIS_MAX + 1e-6) {
        floored++;
      }
    }
    // The hard floor is allowed but must be the exception, not the rule.
    expect(floored).toBeLessThan(40);
    // THE SMALLS live in the scatter pass — the spazas and sheds the old clamp turned into
    // 15 × 21 halls. Each one: single-storey, no core, camera-floor respected, one walkable room.
    let smalls = 0;
    for (const model of allScatteredModels()) {
      if (smalls >= 8) break;
      if (!MODEL_INDEX.get(model.name)?.interior) continue;
      const door = scatterDoorFor(model);
      if (!door) continue;
      const core = buildCore(door.facts);
      if (core.layout !== 'small') continue;
      smalls++;
      expect(core.storeys, `${door.id} multi-storey small`).toBe(1);
      expect(core.stair, `${door.id} small with a stair`).toBeUndefined();
      expect(core.width, `${door.id} camera floor`).toBeGreaterThanOrEqual(MIN_ROOM - 1e-6);
      expect(core.depth, `${door.id} camera floor`).toBeGreaterThanOrEqual(MIN_ROOM - 1e-6);
      const plan = solveFloor(door.facts, 0, core);
      expect(plan.rooms).toHaveLength(1);
      expect(plan.walls).toHaveLength(0);
      expect(plan.unreachable, `${door.id} small layout unreachable`).toBe(0);
    }
    expect(smalls, 'the scatter pass produced no small layouts at all').toBeGreaterThan(3);
  }, 300000);

  /**
   * The owner's placement step 2: the interior entry matches the model's tagged door. The interior
   * frame is the building frame rotated a half turn, so the tag at building-local +x lands at
   * interior-local −x, proportionally scaled where the plate is clamped, held inside the band that
   * keeps a room either side of the corridor.
   */
  it('anchors the corridor on the model-tagged door, proportionally mapped and clamped', () => {
    let offCentre = 0;
    // 300 -> 900: the clamp only leaves slack on cores wider than ~14.5 u, and the CBD-height pass
    // (a low street wall packed with narrow shopfront stands) moved the citywide width mix down
    // far enough that a 300-parcel stride found only two of them. The assertion is unchanged; the
    // sample is simply large enough again to contain the case it is about.
    for (const facts of sample(900)) {
      const core = buildCore(facts);
      if (core.layout === 'small') continue; // the one-room layout clamps the door by its own rule
      const slack = Math.max(0, core.width / 2 - 3.3 / 2 - 5.6);
      const wanted = -facts.doorX * (core.width / Math.max(1, facts.width));
      const expected = Math.max(-slack, Math.min(slack, wanted));
      expect(core.entryX, facts.id).toBe(core.corridorX);
      expect(Math.abs(core.corridorX - expected), `${facts.id}: entry ${core.corridorX} vs door-mapped ${expected}`).toBeLessThan(1e-6);
      if (Math.abs(facts.doorX) > 0.5 && Math.abs(wanted) <= slack) {
        offCentre++;
        expect(Math.sign(core.corridorX), `${facts.id}: off-centre door did not pull the corridor`).toBe(Math.sign(-facts.doorX));
      }
    }
    expect(offCentre, 'the sample found no off-centre tagged doors with room to follow them').toBeGreaterThan(5);
  }, 120000);
});

describe('determinism', () => {
  it('rebuilds the identical floor, second visit and hundredth', () => {
    for (const facts of sample(40)) {
      const core = buildCore(facts);
      for (const index of [0, Math.min(1, core.storeys - 1), core.storeys - 1]) {
        const first = solveFloor(facts, index);
        const again = solveFloor(facts, index);
        expect(again).toEqual(first);
      }
    }
  }, 120000);

  it('generates floor 31 the same whether or not floor 30 was ever generated', () => {
    const tall = sample(400).map(buildCore).find((core) => core.storeys > 32);
    // Not every map has a 32-storey building; when one exists this is the on-demand contract.
    if (!tall) return;
    const facts = sample(400).find((candidate) => buildCore(candidate).id === tall.id)!;
    const cold = solveFloor(facts, 31);
    for (let index = 0; index < 31; index++) solveFloor(facts, index);
    const warm = solveFloor(facts, 31);
    expect(warm).toEqual(cold);
  }, 300000);

  it('does not depend on the order buildings are visited', () => {
    const buildings = sample(12);
    const forwards = buildings.map((facts) => solveFloor(facts, 0));
    const backwards = [...buildings].reverse().map((facts) => solveFloor(facts, 0)).reverse();
    expect(backwards).toEqual(forwards);
  }, 120000);
});
